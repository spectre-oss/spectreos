#!/usr/bin/env python3
"""Regenerate compact loading geometry using pinned upstream shape/morph code.
Requires a JDK only for regeneration. No Java/Kotlin artifacts enter the runtime.
"""
from pathlib import Path
import hashlib,json,subprocess,urllib.request
ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'context/build/shape-export'
ARTIFACTS=[
('shapes.jar','https://dl.google.com/dl/android/maven2/androidx/graphics/graphics-shapes-desktop/1.1.0/graphics-shapes-desktop-1.1.0.jar','8d7a4d3812cae2e3ef8272e97f6e9917ae45931f17cf1391f0246a92c955d9f4'),
('collection.jar','https://dl.google.com/dl/android/maven2/androidx/collection/collection-jvm/1.5.0/collection-jvm-1.5.0.jar','70b35924e4babcdffa37d0e575ee039c56a2d97123342624c48b603233704341'),
('kotlin.jar','https://repo.maven.apache.org/maven2/org/jetbrains/kotlin/kotlin-stdlib/2.1.20/kotlin-stdlib-2.1.20.jar','1bcc74e8ce84e2c25eaafde10f1248349cce3062b6e36978cbeec610db1e930a'),
('animation.jar','https://repo.maven.apache.org/maven2/org/jetbrains/compose/animation/animation-core-desktop/1.8.2/animation-core-desktop-1.8.2.jar','710eeb91fd8552e10b67ecae12b1dc31ab317eb6e5bceb04d4c21e3f34252407')]
def main():
 OUT.mkdir(parents=True,exist_ok=True)
 for name,url,digest in ARTIFACTS:
  path=OUT/name
  if not path.exists():
   with urllib.request.urlopen(url,timeout=60) as response:path.write_bytes(response.read())
  if hashlib.sha256(path.read_bytes()).hexdigest()!=digest:raise SystemExit('Checksum mismatch: '+name)
 subprocess.run(['javac','-cp',str(OUT/'*'),'-d',str(OUT),str(ROOT/'tools/BhooShapes.java')],check=True)
 data=json.loads(subprocess.check_output(['java','-cp',str(OUT)+':'+str(OUT/'*'),'BhooShapes'],text=True))
 def number(v):
  s=format(v,'.9g');return s if '.' in s or 'e' in s else s+'.0'
 lines=['//! Generated by tools/generate-bhoo-loading.py; do not hand edit.',
 '//! Shape recipes: Copyright 2024 The Android Open Source Project, Apache-2.0.',
 '//! AndroidX graphics-shapes 1.1.0 supplies the exact matched cubic geometry.',
 '//! See THIRD_PARTY_NOTICES.md and codes/libs/ui/libbhoo/docs/effects-implementation.md.',
 '#![allow(clippy::excessive_precision,clippy::approx_constant)]',
 'pub const SCALE:f32='+number(data['scale'])+';',
 'pub const MORPH_SECONDS:f64='+number(data['spring_seconds'])+';',
 '#[rustfmt::skip]',
 'pub const SHAPES:[&[[[f32;8];2]];'+str(len(data['pairs']))+']=[']
 for sequence in data['pairs']:
  lines.append('&[')
  for a,b in sequence:lines.append('[[%s],[%s]],'%(','.join(number(v) for v in a),','.join(number(v) for v in b)))
  lines.append('],')
 lines.append('];')
 path=ROOT/'codes/libs/ui/libbhoo/src/shapes/loading_shapes.rs';path.write_text('\n'.join(lines)+'\n')
 subprocess.run(['rustfmt','--edition','2024',str(path)],check=True)
 print('Generated',len(data['pairs']),'matched shape pairs;',path.stat().st_size,'source bytes')
if __name__=='__main__':main()
