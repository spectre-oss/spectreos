#!/usr/bin/env python3
"""Generate Bhoo mesh from Material Android's Apache-2.0 checked-card vector."""
from pathlib import Path
import json, subprocess, sys, xml.etree.ElementTree as ET
root=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(root/'context/build/svgpath'))
from svg.path import parse_path
from svg.path.path import Move,Line,Close
source=root/'codes/libs/ui/libbhoo/assets/material-android/ic_mtrl_checked_circle.xml'
path=ET.parse(source).getroot().find('path').attrib['{http://schemas.android.com/apk/res/android}pathData']
contours=[];points=[]
def point(z):return [round(z.real/24,6),round(z.imag/24,6)]
def flush():
 if len(points)>1 and points[-1]==points[0]:points.pop()
 if len(points)>=3:contours.append(points.copy())
 points.clear()
for segment in parse_path(path):
 if isinstance(segment,Move):flush();points.append(point(segment.end));continue
 for i in range(1,(1 if isinstance(segment,(Line,Close)) else 16)+1):
  n=1 if isinstance(segment,(Line,Close)) else 16
  p=point(segment.point(i/n))
  if not points or p!=points[-1]:points.append(p)
flush()
if len(contours)!=2:raise ValueError('Expected circle and check cutout')
helper=root/'context/build/shape-gen/card-icon.mjs'
helper.write_text("import earcut from './node_modules/earcut/src/earcut.js';let s='';for await(const c of process.stdin)s+=c;let a=JSON.parse(s);process.stdout.write(JSON.stringify(earcut(a.flat(2),[a[0].length],2)));")
triangles=json.loads(subprocess.check_output(['node',str(helper)],input=json.dumps(contours),text=True))
def f(x):
 s=f'{x:.6f}'.rstrip('0').rstrip('.')
 return s if '.' in s else s+'.0'
points=sum(contours,[])
out='''//! Generated by tools/generate-material-card-icon.py from Material Android's
//! ic_mtrl_checked_circle.xml, Copyright 2019 The Android Open Source Project,
//! Apache-2.0. See THIRD_PARTY_NOTICES.md.
use crate::beercss_shapes::ShapeData;
pub static CHECKED: ShapeData = ShapeData { name:"material-android-card-checked", points:&['''+','.join('['+f(x)+','+f(y)+']' for x,y in points)+'], contours:&[0,'+str(len(contours[0]))+','+str(len(points))+'], triangles:&['+','.join(map(str,triangles))+'] };\n'
(root/'codes/libs/ui/libbhoo/src/icons/material_card.rs').write_text(out)
print('Generated checked card icon:',len(points),'points,',len(triangles)//3,'triangles')
