#!/usr/bin/env python3
"""Find isolated bright RAW10 defects repeated in both frames at both gains.

Uses the same retained dark4/dark16 pairs as calibrate-noise.py. Produces a
per-device map, never a general IMX363 defect list. No builds or phone writes.
"""
import argparse
import hashlib
import importlib.util
import json
from pathlib import Path
import numpy as np
s=importlib.util.spec_from_file_location('noise',Path(__file__).with_name('calibrate-noise.py'))
noise=importlib.util.module_from_spec(s);s.loader.exec_module(noise)

def detect(directory):
    candidates=[]; sources={}
    for name,sigma in [('dark4',1.8),('dark16',5.2)]:
        path=directory/(name+'-pair.raw'); arrays=noise.unpack(path); masks=[]
        for frame in arrays:
            neighbours=np.stack([frame[2+dy:3022+dy,2+dx:4030+dx] for dy,dx in
                [(-2,0),(2,0),(0,-2),(0,2),(-2,-2),(-2,2),(2,-2),(2,2)]])
            median=np.median(neighbours,axis=0)
            masks.append((frame[2:-2,2:-2]-median>max(32,8*sigma)) & (median<85))
        y,x=np.where(masks[0]&masks[1]);candidates.append(set(zip((x+2).tolist(),(y+2).tolist())))
        sources[name]=hashlib.sha256(path.read_bytes()).hexdigest()
    points=sorted(candidates[0]&candidates[1],key=lambda p:(p[1],p[0]))
    if len(points)>2048:raise ValueError('Implausibly many defects: check covered-lens inputs')
    return {'schema':1,'camera':'beryllium-imx363-sunny','size':[4032,3024],'cfa':'RGGB',
            'blackLevel':64,'digitalGain':256,'points':points,'sha256':sources,
            'method':'At least 32 RAW codes and eight read-noise sigmas above the same-CFA eight-neighbour median in all four covered-lens frames; reject non-dark neighbours.',
            'limitations':'This physical module only. Temperature and exposure coverage limited; not a factory dead-pixel map. Borders excluded. No normal-scene outlier detection.'}

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('directory',type=Path);p.add_argument('--output',type=Path,required=True);p.add_argument('--header',type=Path,required=True);a=p.parse_args()
    r=detect(a.directory);a.output.write_text(json.dumps(r,indent=2)+'\n')
    points=',\n'.join('    {%d, %d}'%tuple(v) for v in r['points'])
    a.header.write_text('// Generated by calibrate-defects.py; this physical Sunny module only.\n#pragma once\n#include <array>\n#include <cstdint>\nnamespace spectre {\nstruct DefectPoint { uint16_t x, y; };\ninline constexpr std::array<DefectPoint, %d> sunnyDefects = {{\n%s\n}};\n}\n'%(len(r['points']),points))
    print('Detected',len(r['points']),'repeatable bright defects across both gains.')
