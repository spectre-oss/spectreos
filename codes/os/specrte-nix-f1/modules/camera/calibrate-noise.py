#!/usr/bin/env python3
"""Fit a RAW10 temporal noise model from retained, fixed-control frame pairs.

Input directory: dark4-pair.raw, dark16-pair.raw, scene4-pair.raw, each two
4032x3024 tightly packed frames at digital gain 256. The scene pair must have
the same exposure/lighting/viewpoint. This is data analysis, not a phone build.
"""
import argparse
import hashlib
import json
from pathlib import Path
import numpy as np


def unpack(path):
    data = path.read_bytes()
    if len(data) != 2 * 4032 * 3024 * 5 // 4:
        raise ValueError(f"Unexpected RAW10 pair size: {path}")
    packed = np.frombuffer(data, np.uint8).reshape(2, 3024, 1008, 5).astype(np.uint16)
    raw = np.empty((2, 3024, 4032), np.float32)
    for k in range(4):
        raw[:, :, k::4] = (packed[:, :, :, k] << 2) | ((packed[:, :, :, 4] >> (2*k)) & 3)
    return raw


def fit(directory):
    names = ['dark4', 'dark16', 'scene4']
    arrays = {name: unpack(directory / (name + '-pair.raw')) for name in names}
    channels = []
    for y, x, name in [(0, 0, 'R'), (0, 1, 'Gr'), (1, 0, 'Gb'), (1, 1, 'B')]:
        variances = []
        for dark in ['dark4', 'dark16']:
            a = arrays[dark][:, y::2, x::2]
            diff = a[1] - a[0]
            # Temporal differencing removes static scene and fixed-pattern terms.
            variances.append(float(np.var(diff, dtype=np.float64) / 2))
        a = arrays['scene4'][:, y::2, x::2]
        mean, diff = (a[1]+a[0])/2, a[1]-a[0]
        bins = []
        for lo, hi in [(72, 88), (88, 112), (112, 160), (160, 224), (224, 320), (320, 448)]:
            mask = (mean >= lo) & (mean < hi)
            n = int(mask.sum())
            if n < 2000:
                continue
            delta = diff[mask]
            # Reject lighting/motion bias; this is not a substitute for a flat-field sweep.
            if abs(float(delta.mean())) > 1.0:
                continue
            bins.append({'signal': float(mean[mask].mean()-64),
                         'variance': float(np.var(delta, dtype=np.float64)/2), 'pixels': n})
        if len(bins) < 3:
            raise ValueError(f'Insufficient stable signal bins for {name}')
        s = np.array([b['signal'] for b in bins])
        v = np.array([b['variance'] for b in bins])
        slope = float(np.dot(s, v-variances[0])/np.dot(s, s))
        if not 0.01 < slope < 4:
            raise ValueError(f'Implausible shot-noise slope for {name}: {slope}')
        channels.append({'cfa': name, 'readVariance4': variances[0],
                         'readVariance16': variances[1], 'shotSlope4': slope, 'bins': bins})
    return {'version': 1, 'sensor': 'IMX363 Sunny', 'units': 'RAW10 code variance',
            'blackLevel': 64, 'digitalGain': 256, 'gainRange': [1, 16],
            'source': '2026-10-20 retained fixed-control captures: dark exposure 3126 lines; scene exposure 1000 lines',
            'limitations': 'Read noise measured at 4x/16x; shot slope estimated from one stationary scene at 4x. Gain interpolation/extrapolation is a model, not a factory flat-field calibration. Temperature dependence unmeasured.',
            'sha256': {n: hashlib.sha256((directory/(n+'-pair.raw')).read_bytes()).hexdigest() for n in names},
            'channels': channels}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('directory', type=Path)
    parser.add_argument('--output', required=True, type=Path)
    parser.add_argument('--header', required=True, type=Path)
    args = parser.parse_args()
    result = fit(args.directory)
    args.output.write_text(json.dumps(result, indent=2)+'\n')
    rows = ',\n'.join('    {%.9ff, %.9ff, %.9ff}' % (c['readVariance4'], c['readVariance16'], c['shotSlope4']) for c in result['channels'])
    args.header.write_text('''// Generated by calibrate-noise.py; see imx363-noise-profile.json for provenance.
#pragma once
#include <algorithm>
#include <cmath>
namespace spectre {
inline constexpr float noiseCoefficients[4][3] = {
'''+rows+'''
};
inline float rawNoiseVariance(float signal, float gain, unsigned cfa) {
    gain = std::isfinite(gain) ? std::clamp(gain, 1.0f, 16.0f) : 4.0f;
    const auto &c = noiseCoefficients[cfa & 3];
    const float read = std::max(0.25f, c[0] + (c[1]-c[0])*(gain*gain-16.0f)/240.0f);
    return read + c[2]*(gain/4.0f)*std::max(0.0f, signal);
}
}
''')
    print(json.dumps(result, indent=2))
